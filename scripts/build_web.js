function buildBundle(entryId, selectedModuleFiles, selectedVirtualModules = []) {
  const modulesSource = Object.entries(selectedModuleFiles)
    .map(([id, filePath]) => {
    const code = compileTs(filePath);
    return `${jsString(normalizeModuleId(id))}: function(require, module, exports) {\n${code}\n}`;
  })
  .concat(selectedVirtualModules.map(id => `${jsString(id)}: function(require, module, exports) {\n${virtualModules[id]}\n}`))
  .join(',\n');

  return `// Generated by scripts/build_web.js. Do not edit directly.
(function () {
  var modules = {
${modulesSource}
  };
  var cache = {};
  function resolve(from, request) {
    if (request.charAt(0) !== '.') return request;
    var parts = from.split('/');
    parts.pop();
    var raw = parts.concat(request.split('/'));
    var out = [];
    for (var i = 0; i < raw.length; i++) {
      var part = raw[i];
      if (!part || part === '.') continue;
      if (part === '..') out.pop();
      else out.push(part);
    }
    return out.join('/').replace(/\\.(js|ts)$/, '');
  }
  function load(id) {
    if (cache[id]) return cache[id].exports;
    if (!modules[id]) throw new Error('Module not found: ' + id);
    var module = { exports: {} };
    cache[id] = module;
    modules[id](function (request) { return load(resolve(id, request)); }, module, module.exports);
    return module.exports;
  }
  load(${jsString(entryId)});
}());
`;
}

function readTemplateSources() {
  const templatesDir = path.join(projectRoot, 'src/templates');
  return fs.readdirSync(templatesDir)
    .filter(name => name.endsWith('.md'))
    .map(name => ({ fileName: name, markdown: fs.readFileSync(path.join(templatesDir, name), 'utf-8') }));
}

function readDraftingData() {
  const rulesPath = path.join(projectRoot, 'src/base/court_doc_rules.md');
  const sources = readTemplateSources();
  const byName = new Map(sources.map(source => [source.fileName, source]));
  const templates = templateCatalog.sortTemplateNames(sources.map(source => source.fileName))
    .map(name => {
      const parsed = templateCatalog.splitTemplateAiNotes(byName.get(name).markdown);
      return {
        id: name,
        name: templateCatalog.templateDisplayName(name),
        group: templateCatalog.getTemplateGroup(name),
        content: parsed.content,
        aiNotes: parsed.aiNotes
      };
    });

  return {
    generatedAt: new Date().toISOString(),
    rules: fs.readFileSync(rulesPath, 'utf-8'),
    templates
  };
}

function readArchiveData() {
  const baseDir = path.join(projectRoot, 'src/base');
  const sources = readTemplateSources();
  const instructions = [
    {
      displayPath: 'instructions/00_START_HERE.md',
      content: draftingKit.buildStartHere(sources.map(source => source.fileName), 'archive'),
      isCommonRules: false,
      isWorkflowGuide: true,
      isTeamGuide: false
    }
  ];

  const virtualTeamInstructionPath = path.join(projectRoot, 'docs', virtualTeamInstructionFileName);
  if (fs.existsSync(virtualTeamInstructionPath)) {
    instructions.push({
      displayPath: `instructions/${virtualTeamInstructionFileName}`,
      content: buildVirtualTeamArchiveInstructionContent(fs.readFileSync(virtualTeamInstructionPath, 'utf-8')),
      isCommonRules: false,
      isWorkflowGuide: false,
      isTeamGuide: true
    });
  }

  const ruleFiles = draftingKit.buildRuleInstructionFiles({
    rules: fs.readFileSync(path.join(baseDir, 'court_doc_rules.md'), 'utf-8'),
    sample: fs.readFileSync(path.join(baseDir, 'sample.md'), 'utf-8'),
    templates: sources
  });
  for (const file of ruleFiles) {
    instructions.push({
      displayPath: `instructions/${file.name}`,
      content: file.content,
      isCommonRules: file.name === 'sample.md',
      isWorkflowGuide: false,
      isTeamGuide: false
    });
  }

  return {
    generatedAt: new Date().toISOString(),
    instructions
  };
}

