const fs = require('fs');
const out = process.argv[2];
const rows = [];
const subjects = ['売買契約書', '領収証', 'メール送信履歴', '陳述書', '写真撮影報告書', '診断書', '請求書', '内容証明郵便', '通話録音反訳書', 'ウェブサイト印刷物'];
for (let i = 1; i <= 40; i++) {
  const num = i % 7 === 0 ? `${i}-1` : String(i);
  const subject = subjects[i % subjects.length];
  const purpose = i % 5 === 0
    ? `被告が令和5年${(i % 12) + 1}月${(i % 27) + 1}日頃、原告に対し、本件契約に基づく代金の支払を拒絶する旨を通知し、その後も原告からの再三の催告にもかかわらず支払に応じなかった事実、及び被告が支払を拒んだ理由として主張する事情がいずれも本件契約の締結時に既に明らかであった事実`
    : `本件${subject}の作成経過と、原告が被告に対して${subject}の内容を説明した事実`;
  rows.push(`| ${num} | ${subject} | ${i % 2 ? '原本' : '写し'} | 令和5年${(i % 12) + 1}月${(i % 27) + 1}日 | 甲野太郎 | ${purpose} |`);
}
const md = `### --左
令和6年（ワ）第123号　損害賠償請求事件
- 原告:甲野　太郎
- 被告:乙山　次郎
### --

# 証拠説明書

### --左
東京地方裁判所民事第1部　御中
### --

令和6年5月1日

### --右
- 原告:甲野　太郎
### --

| 甲号証 | 標目 | 原本写 | 作成年月日 | 作成者 | 立証趣旨 |
| :--- | :--- | :---: | :--- | :--- | :--- |
${rows.join('\n')}
`;
fs.writeFileSync(out, md, 'utf-8');
