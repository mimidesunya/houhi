// 頁より長い行と、頁をまたぐ枝番（rowspan）の入った証拠説明書を作る
// usage: node make_table_doc.js <out.md>
const fs = require('fs');
const long = '被告が原告に対し、本件契約に基づく代金の支払を拒絶する旨を通知した事実、'.repeat(30) + 'その他の事実';
let md = '# 証拠説明書\n\n| 甲号証 | 標目 | 原本写 | 作成年月日 | 作成者 | 立証趣旨 |\n| :--- | :--- | :---: | :--- | :--- | :--- |\n';
for (let i = 1; i <= 6; i++) md += `| ${i} | 領収証 | 原本 | 令和5年${i}月${i}日 | 甲野太郎 | 本件領収証の作成経過と、原告が被告に対して領収証の内容を説明した事実 |\n`;
md += `| 7 | 陳述書 | 原本 | 令和5年7月7日 | 甲野太郎 | ${long} |\n`;
md += `| 8-1 | 写真 | 写し | 令和5年8月8日 | 甲野太郎 | 現場の状況。枝番の行は作成年月日・作成者・立証趣旨を空欄にして上の行と結合する |\n`;
for (let j = 2; j <= 12; j++) md += `| 8-${j} | 写真 | 写し | | | |\n`;
md += `| 9 | 請求書 | 写し | 令和5年9月9日 | 甲野太郎 | 本件請求書の作成経過 |\n`;
fs.writeFileSync(process.argv[2], md);
